numeroA = float(input("Qual o primeiro número? "))
numeroB = float(input("Qual o segundo número? "))

soma = numeroA + numeroB
sub = numeroA - numeroB
mult = numeroA * numeroB
div = numeroA / numeroB

print(f"A soma dos seus números escolhidos é de {soma}, a subtração é de {sub}, a multiplicação de {mult} e a divisão é de {div}.")